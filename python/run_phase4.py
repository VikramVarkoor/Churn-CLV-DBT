"""
Phase 4 orchestration: for each segment in docs/evidence/segment_stats.json, builds the
prompt (python/llm/prompts.py), gets a summary from an LLMClient (python/llm/client.py), and
verifies it (python/llm/verify.py). Writes docs/evidence/p4_llm_summaries.md (human-readable
report) and docs/evidence/p4_llm_raw.json (model name, prompt, and date for every output, per
docs/design.md's audit requirement). Identical orchestration either way -- only which client
is constructed changes.

Usage (from the project root):
    python3 python/run_phase4.py --stub       # offline, deterministic, no API key needed
    python3 python/run_phase4.py               # real Groq call; requires GROQ_API_KEY

Requires docs/evidence/segment_stats.json to already exist -- run
`python3 python/build_segment_stats.py` first.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from llm.client import GroqClient, StubClient  # noqa: E402
from llm.prompts import build_prompt  # noqa: E402
from llm.verify import verify_summary  # noqa: E402

SEGMENT_STATS_PATH = Path("docs/evidence/segment_stats.json")
REPORT_PATH = Path("docs/evidence/p4_llm_summaries.md")
RAW_LOG_PATH = Path("docs/evidence/p4_llm_raw.json")


def load_segment_stats(path: Path = SEGMENT_STATS_PATH) -> dict:
    if not path.exists():
        raise FileNotFoundError(
            f"{path} does not exist. Run `python3 python/build_segment_stats.py` first -- "
            "that script builds this file from the dbt warehouse."
        )
    return json.loads(path.read_text())


def run(stats: dict, client) -> list[dict]:
    valid_segment_ids = {s["segment_id"] for s in stats["segments"]}
    results = []
    for segment in stats["segments"]:
        prompt = build_prompt(segment)
        output = client.complete(prompt)
        verdict = verify_summary(output.text, segment, valid_segment_ids)
        results.append({
            "segment": segment,
            "output": {
                "text": output.text,
                "model": output.model,
                "prompt": output.prompt,
                "generated_at": output.generated_at,
                "temperature": output.temperature,
            },
            "verdict": verdict,
        })
    return results


def format_report(results: list[dict], stats: dict, client_label: str) -> str:
    lines = []
    lines.append("# Phase 4 LLM segment summaries\n")
    lines.append(f"Generated: {dt.date.today().isoformat()}. Client: {client_label}.\n")
    lines.append(
        f"Population cutoff: {stats['population_cutoff']}. CLV horizon: "
        f"{stats['clv_horizon_days']} days. Segment numbers are from "
        f"{SEGMENT_STATS_PATH}, generated by python/build_segment_stats.py.\n"
    )

    n_passed = sum(1 for r in results if r["verdict"]["passed"])
    lines.append(f"## Verification summary: {n_passed}/{len(results)} summaries passed\n")

    for r in results:
        segment = r["segment"]
        verdict = r["verdict"]
        status = "PASS" if verdict["passed"] else "FAIL"
        lines.append(f"## Segment {segment['segment_id']} -- {status}\n")
        lines.append(
            f"n_customers={segment['n_customers']}, "
            f"share_of_customers={segment['share_of_customers']}, "
            f"share_of_revenue={segment['share_of_revenue']}, "
            f"mean_recency_days={segment['mean_recency_days']}, "
            f"mean_frequency={segment['mean_frequency']}, "
            f"mean_monetary_net={segment['mean_monetary_net']}, "
            f"predicted_churn_rate={segment['predicted_churn_rate']}, "
            f"predicted_clv_245d={segment['predicted_clv_245d']}\n"
        )
        lines.append(f"> {r['output']['text']}\n")
        if not verdict["passed"]:
            lines.append(
                f"Flagged: unsupported_numbers={verdict['unsupported_numbers']}, "
                f"unsupported_segments={verdict['unsupported_segments']}, "
                f"causal_markers={verdict['causal_markers']}\n"
            )
        lines.append(f"Model: {r['output']['model']}. Generated: {r['output']['generated_at']}.\n")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--stub", action="store_true",
        help="Use the deterministic offline StubClient instead of the real Groq API.",
    )
    args = parser.parse_args()

    stats = load_segment_stats()
    client = StubClient() if args.stub else GroqClient()
    client_label = "StubClient (offline, deterministic)" if args.stub else f"GroqClient ({client.model})"

    results = run(stats, client)

    report = format_report(results, stats, client_label)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report)

    raw_log = [
        {
            "segment_id": r["segment"]["segment_id"],
            "model": r["output"]["model"],
            "generated_at": r["output"]["generated_at"],
            "temperature": r["output"]["temperature"],
            "prompt": r["output"]["prompt"],
            "response_text": r["output"]["text"],
            "verdict": r["verdict"],
        }
        for r in results
    ]
    RAW_LOG_PATH.write_text(json.dumps(raw_log, indent=2) + "\n")

    print(report)
    n_passed = sum(1 for r in results if r["verdict"]["passed"])
    print(f"\n{n_passed}/{len(results)} summaries passed verification.")
    print(f"Written to {REPORT_PATH} and {RAW_LOG_PATH}")


if __name__ == "__main__":
    main()
